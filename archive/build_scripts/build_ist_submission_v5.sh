#!/usr/bin/env bash
# Stage 5 FINALIZE v5: Build IST submission package using elsarticle.
# Differences vs v1 (build_ist_submission.sh):
#   - Source = IST-trimmed body (论文初稿P2_IST.md, 9.5k words)
#   - Adds \begin{highlights} block (5 bullets, max 85 chars each)
#   - Concatenates 论文初稿P2_IST_appendix.md after \appendix directive
#   - Embeds 3 figures (figs/fig{1,2,3}*.png) via \includegraphics
#   - Strips H1 + Highlights + Abstract + Keywords markdown
#     before pandoc (these go into elsarticle macros, not body).
# Inputs : 论文初稿P2_IST.md + 论文初稿P2_IST_appendix.md + figs/*.png
# Outputs: submission/p2_ist_v5.{tex,pdf}
# Tools  : pandoc 3.9, xelatex (texlive), elsarticle.cls in submission/texmf/
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
OUT="submission"
mkdir -p "$OUT"

MAIN_MD="论文初稿P2_IST.md"
APX_MD="论文初稿P2_IST_appendix.md"

# 1) Extract main-body (skip H1 title + Highlights + Abstract + Keywords + ---)
#    These four sections become elsarticle macros, not body content.
#    Body starts at "## 1. Introduction" (line 21 in current file).
sed -n '/^## 1\. Introduction/,$p' "$MAIN_MD" > "$OUT/_main_body.md"

# 1b) Inject figure references at natural anchors.
#     fig1 (three-layer methodology) → after §1.2 Three-layer methodological framework
#     fig2 (60-cell heatmap)         → in §5 Statistics+Results, after H1 metric block
#     fig3 (AST overlap per class)   → in §3.5 12-PUT empirical
python3 - <<'PYEOF'
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent if False else Path(".")
src = ROOT / "submission" / "_main_body.md"
text = src.read_text(encoding="utf-8")

FIG1 = """

![Three-layer methodological framework: Layer 1 (definitional necessary conditions), Layer 2 (operational $E_1 \\wedge E_2$ judgement), Layer 3 (applied AST-normalised traceability across 12 PUTs).](../figs/fig1_three_layer_methodology.png){#fig:framework width=85%}

"""
FIG2 = """

![60-cell heatmap of mean SMS over 12 PUTs $\\times$ 5 MPs (v4 cross-source primary). Diagonal cells (operator-MP aligned) show concentrated mass; off-diagonal mass reflects bleed into adjacent MPs. Empty rows = PUT-level zero-mass cohort (PUTs A1, B1, D2; see §6.2).](../figs/fig2_60cell_heatmap.png){#fig:heatmap width=90%}

"""
FIG3 = """

![Per-class AST overlap rate between 292 P2 mutants and 1,250 cosmic-ray syntactic mutants across 12 PUTs (overall 5.14%). HP, SI, TF (54.5% of P2 pool) are categorically unreachable (0/72, 0/33, 0/54); CE 7.81%, OS 11.67%, CF 33.33% (CF is a class-specialisation, not in main 5).](../figs/fig3_ast_overlap_per_class.png){#fig:overlap width=80%}

"""

# Anchor 1: end of §1.2 (look for §1.3 heading, insert before it)
text = text.replace("\n### 1.3 Related work and roadmap\n",
                    FIG1 + "\n### 1.3 Related work and roadmap\n", 1)
# Anchor 2: opening of §5 Results — first figure-worthy spot is §5.5 or
# right before §5.6 Aggregated tables. We insert after the §5 H2.
# Look for "## 5. " heading and append fig immediately under the section
# intro paragraph (heuristic: insert before "### 5.1").
text = text.replace("\n### 5.1",
                    FIG2 + "\n### 5.1", 1)
# Anchor 3: §3.5 12-PUT empirical — look for §3.5 heading.
text = text.replace("\n### 3.5",
                    FIG3 + "\n### 3.5", 1)

src.write_text(text, encoding="utf-8")
print("Figures injected at 3 anchors")
PYEOF

# 1c) Append appendix body (with \appendix directive injected as raw LaTeX)
#     The appendix MD starts with "# Appendix"; we strip that H1 since
#     elsarticle's \appendix produces its own section numbering.
{
  printf '\n\n\\appendix\n\n'
  sed -n '/^## A\./,$p' "$APX_MD"
} >> "$OUT/_main_body.md"

# 2) Pandoc → LaTeX body. top-level-division=section so H2 → \section,
#    H3 → \subsection.
pandoc "$OUT/_main_body.md" \
  --from markdown+pipe_tables+raw_tex+tex_math_dollars+fenced_code_blocks \
  --to latex \
  --top-level-division=section \
  --listings \
  --no-highlight \
  -o "$OUT/_main_body.tex"

# 3) DOCX intermediate (review-track convenience)
pandoc "$MAIN_MD" -o "$OUT/p2_ist_v5.docx"

