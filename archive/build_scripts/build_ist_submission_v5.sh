\begin{abstract}
\noindent\textbf{Context.} Metamorphic Testing addresses the test-oracle problem in scientific computing, but classical Mutation Score (MS) operates on syntactic AST mutations and misses domain semantics.
\textbf{Objective.} We propose Semantic Mutation Score (SMS), built on five domain-semantic operators (Conservation Erosion, Operator Substitution, Hyperparameter, Trajectory Flip, Structural Injection); SMS degenerates almost everywhere to MS in a characterised limit.
\textbf{Method.} A 12-PUT $\times$ 5-MP matrix (60 cells; mean 24.3 mutants/PUT; $N=20$ AVP repetitions) over four single-output \texttt{float}~$\to$~\texttt{float} classes (numeric / probabilistic / surrogate / ML; $<$ 2 KB each). A three-layer LRCA classifier separates true semantic faults from artefacts / tolerance / OOD / noise. A three-stage ablation (v3 same-source; v3b data-driven primary MP; v4 cross-source over Claude / GPT / DeepSeek under identical prompt) isolates MR-design vs LLM-source-diversity contributions.
\textbf{Results.}
\textit{Primary verdict (v3, pre-registered).} The H2 large-effect threshold (Cliff's $\delta \geq 0.474$, Romano 2006) is \emph{not met} under the point-estimate criterion: $\delta_{v3} = 0.323$ (95\% CI $[0.017, 0.622]$). Stipulated-alternative power at $\delta_{\text{truth}} = 0.474$ is $49.1\%$, so ``not met'' describes the point estimate, not the underlying effect size.
\textit{Robustness (v4-mp5, strips R11).} Holding the c-class primary at the pre-registered MP5 while pooling across LLM sources gives $\delta_{v4\text{-mp5}} = 0.314$ (95\% CI $[0.014, 0.622]$); the contrast against v3 is $\Delta\delta = -0.009$ (LLM-source axis under MP5).
\textit{Exploratory (v3b / v4-mp1, post-hoc selection).} v3b reaches $0.446^{\dagger}$ (data-driven c-class primary MP, same-source); v4-mp1 reaches $0.439^{\dagger}$ (cross-source, MP1); $\Delta\delta(\text{v3b}\to\text{v4-mp1}) = -0.007$. Across both MP conditions, the cross-source axis shifts $\delta$ by $\leq 0.01$ in magnitude, while the MR-design axis (MP5 $\leftrightarrow$ MP1) shifts $\delta$ by approximately $+0.12$.
\textit{Other.} Cross-source pooling raises mean $C_1$\_share $0.164 \to 0.209$ and class-c SMS by $+91.4\%^{\dagger}$ without moving $\delta$. Friedman $\chi^2 = 15.30$, $p = 0.0041$. AST overlap with cosmic-ray is $5.14\%$; the Hyperparameter, Structural Injection, and Trajectory Flip classes (159 of 292 mutants) are categorically unreachable by \textbf{first-order} syntactic tools (0/0/0). ($^{\dagger}$ v3b/v4-derived numbers depend on the \S3.4 post-hoc c-class primary-MP shift; permutation null one-sided $p = 0.9885$.)
\textbf{Conclusion.} Within this design, the MR-design axis (c-class primary-MP choice) is the lever on the aligned-vs-cross effect size; the LLM-identity axis (Claude / GPT / DeepSeek under an identical prompt) shifts $\delta$ by $\leq 0.01$ across two MP conditions. The strong-sense source-diversity test with per-LLM differential prompts is deferred to P4. The \S3.5 evidence (5.14\% AST overlap, 0/0/0 unreachability for HP / SI / TF under first-order syntactic tools) is independent of this caveat. SMS is a backward-compatible adequacy metric for domain-semantic MR sets.
\end{abstract}

