#!/usr/bin/env bash
# R-15 (P2) NEW-MAJOR-1 generalization: cosmic-ray ablation on a single PUT.
# Generalized from scripts/run_cosmic_ray_a1.sh to take a PUT_ID argument
# (e.g. a1, a2, ..., d3) so the user can run cosmic-ray on each PUT
# without further editing.
#
# Demonstrates that first-order syntactic mutation tools generate mutants
# whose structure stays AST-local and does NOT cover P2's OS/HP/TF/SI
# operator classes (per §3.2.6.1 operator-level cross-table).
#
# Wall-clock estimate: 5–15 min per PUT on a 4-core laptop, depending on
# baseline test runtime. 12 PUTs total -> 1-3 hours wall time.
#
# Run from repo root:
#   bash scripts/run_cosmic_ray_put.sh <PUT_ID>
# Examples:
#   bash scripts/run_cosmic_ray_put.sh a1
#   bash scripts/run_cosmic_ray_put.sh b2
#
# Output:
#   data/results/cosmic_ray_${PUT_ID}_summary.json
#   data/results/cosmic_ray_${PUT_ID}_console.log
#   data/results/cosmic_ray_${PUT_ID}.sqlite
#
# This script is gated behind explicit invocation (not part of CI) because:
# (a) cosmic-ray is not in requirements-frozen.txt by default;
# (b) the result is supplementary to §3.2.6.1 which already closes R-15
#     at the operator-level argument.
set -euo pipefail

if [ $# -lt 1 ]; then
  echo "Usage: $0 <PUT_ID>" >&2
  echo "  Example: $0 a1" >&2
  exit 1
fi

PUT_ID="$1"

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

# Validate that the PUT source and primary test file exist
PUT_SRC="src/p2/puts/${PUT_ID}.py"
PUT_TEST="tests/puts/test_${PUT_ID}.py"

if [ ! -f "$PUT_SRC" ]; then
  echo "ERROR: PUT source not found: $PUT_SRC" >&2
  exit 1
fi
if [ ! -f "$PUT_TEST" ]; then
  echo "ERROR: PUT test not found: $PUT_TEST" >&2
  exit 1
fi

if [ ! -d ".venv" ]; then
  echo "ERROR: .venv not found; run python3.12 -m venv .venv first" >&2
  exit 1
fi

# Collect all matching test files (e.g. a1 has both test_a1.py and
# test_a1_scalar_interface.py; most PUTs have only test_<id>.py).
shopt -s nullglob
TEST_FILES=( tests/puts/test_${PUT_ID}.py tests/puts/test_${PUT_ID}_*.py )
shopt -u nullglob
TEST_FILES_STR="${TEST_FILES[*]}"
echo "Test files for ${PUT_ID}: ${TEST_FILES_STR}"

# 1. Install cosmic-ray into the venv (one-time)
.venv/bin/pip install -q "cosmic-ray>=8" || {
  echo "pip install cosmic-ray failed" >&2
  exit 1
}

# 2. Generate per-PUT pytest wrapper script (cosmic-ray's subprocess.run
# uses shlex.split which doesn't honor VAR=val command prefixes; so we
# need a wrapper that sets PYTHONPATH=src and execs the venv pytest).
WRAPPER="scripts/_cr_${PUT_ID}_pytest.sh"
cat > "$WRAPPER" <<EOF
#!/usr/bin/env bash
# AUTO-GENERATED by scripts/run_cosmic_ray_put.sh for PUT_ID=${PUT_ID}
# Wrapper to set PYTHONPATH for cosmic-ray's subprocess.run() invocation.
cd "\$(dirname "\$0")/.."
PYTHONPATH=src exec .venv/bin/pytest -q ${TEST_FILES_STR}
EOF
chmod +x "$WRAPPER"

# 3. Write a per-PUT cosmic-ray TOML config
CONF=".cr-${PUT_ID}.toml"
cat > "$CONF" <<TOML
[cosmic-ray]
module-path = "${PUT_SRC}"
timeout = 30
excluded-modules = []
test-command = "bash ${WRAPPER}"

[cosmic-ray.distributor]
name = "local"
TOML

# 4. Initialize session and execute mutants
SESSION="data/results/cosmic_ray_${PUT_ID}.sqlite"
LOG="data/results/cosmic_ray_${PUT_ID}_console.log"
SUMMARY="data/results/cosmic_ray_${PUT_ID}_summary.json"

mkdir -p data/results
rm -f "$SESSION"

{
  echo "=== cosmic-ray init (PUT=${PUT_ID}) ==="
  .venv/bin/cosmic-ray init "$CONF" "$SESSION"
  echo
  echo "=== cosmic-ray baseline ==="
  .venv/bin/cosmic-ray --verbosity=INFO baseline "$CONF" || {
    echo "BASELINE FAILED: tests don't pass on the unmutated module"
    exit 2
  }
  echo
  echo "=== cosmic-ray exec ==="
  .venv/bin/cosmic-ray exec "$CONF" "$SESSION"
  echo
  echo "=== cosmic-ray dump ==="
  .venv/bin/cr-rate "$SESSION"
  echo
  echo "=== Per-operator counts ==="
  .venv/bin/cr-report "$SESSION" --show-output > /dev/null
  .venv/bin/cr-report "$SESSION" 2>&1 | head -200
} 2>&1 | tee "$LOG"

# 5. Build a JSON summary suitable for paper §3.2.6.2
.venv/bin/python - "$PUT_ID" "$LOG" "$SUMMARY" "$PUT_SRC" "$TEST_FILES_STR" <<'PY'
import json
import re
import sys
from pathlib import Path

put_id, log_path, summary_path, put_src, test_files_str = sys.argv[1:6]
LOG = Path(log_path).read_text()

m = re.search(r"Survival rate:\s*([0-9.]+)%", LOG)
survival = float(m.group(1)) / 100 if m else None

def grab(pat):
    m = re.search(pat, LOG)
    return int(m.group(1)) if m else None

total = grab(r"total\s+jobs:\s*(\d+)") or grab(r"(\d+)\s+total")
killed = grab(r"killed:\s*(\d+)") or grab(r"(\d+)\s+killed")
survived = grab(r"surviv\w*:\s*(\d+)") or grab(r"(\d+)\s+survived")
incompetent = grab(r"incompetent:\s*(\d+)")

summary = {
    "tool": "cosmic-ray",
    "put_id": put_id,
    "target_put": put_src,
    "test_suite": test_files_str,
    "mutants_total": total,
    "killed": killed,
    "survived": survived,
    "incompetent": incompetent,
    "survival_rate": survival,
    "interpretation": (
        "Per §3.2.6.1, cosmic-ray's default operators are AST-local "
        "(BinOp/Compare/BoolOp/etc.); none can express OS/HP/TF/SI. The "
        "mutant kill rate observed here reflects only that subset of P2's "
        "five operator classes that maps to CE-style literal edits. The "
        "qualitative implication — syntactic tools cover at most 1/5 of "
        "P2's semantic operator space — is robust to the specific kill "
        "rate value observed."
    ),
}

Path(summary_path).write_text(
    json.dumps(summary, indent=2, ensure_ascii=False))
print(json.dumps(summary, indent=2, ensure_ascii=False))
PY

echo
echo "Summary saved -> $SUMMARY"
echo "Full log     -> $LOG"
echo "SQLite db    -> $SESSION"
