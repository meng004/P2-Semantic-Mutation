#!/usr/bin/env bash
# Stage 5 FINALIZE: Build IST submission package using elsarticle.
# Inputs : 论文初稿P2_EN.md (post-revision, post-Stage-4.5 PASS)
# Outputs: submission/p2_ist.{tex,pdf}, submission/p2_ist.docx
# Tools  : pandoc 3.9, xelatex (texlive), latexmk
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
OUT="submission"
mkdir -p "$OUT"

SRC_MD="论文初稿P2_EN.md"

# 1) Extract title (markdown line 5), then strip the meta-preamble
#    (lines 1-28: P2 论文初稿 wrapper + abstract + keywords + meta block).
#    Body for elsarticle starts at line 29 (Section 1).
sed -n '29,$p' "$SRC_MD" > "$OUT/_body.md"

# 2) Pandoc → LaTeX body. We strip H1/H2 sectioning into elsarticle
#    \section / \subsection levels by demoting one level.
.venv/bin/pip install -q pypandoc 2>/dev/null || true
pandoc "$OUT/_body.md" \
  --from markdown+pipe_tables+raw_tex+tex_math_dollars \
  --to latex \
  --top-level-division=section \
  --listings \
  --no-highlight \
  -o "$OUT/_body.tex"

# 3) DOCX intermediate (for review-track usage; not the IST submission)
pandoc "$SRC_MD" -o "$OUT/p2_ist.docx"

# 4) Hand-wrap with elsarticle template
cat > "$OUT/p2_ist.tex" <<'PREAMBLE'
